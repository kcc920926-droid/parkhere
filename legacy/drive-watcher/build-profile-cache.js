/*
 * Pre-drives the fixed-seed history and validation days so the tendency page opens instantly.
 * Run from the repository root: node legacy/drive-watcher/build-profile-cache.js
 * profile-cache.test.js checks that the file still matches live drives.
 */
const fs = require("node:fs");
const path = require("node:path");
const { drivers, run, planHistory, planEvaluation } = require("./profile-model.js");

const cache = Object.fromEntries(drivers.map((driver) => [driver.id, {
  history: planHistory(driver).map(run),
  evaluation: planEvaluation(driver).map((entry) => run(entry.params)),
}]));

const body = `/* Generated by build-profile-cache.js from fixed seeds. Do not edit by hand. */
const DriveWatcherProfileCache = ${JSON.stringify(cache)};
if (typeof module !== "undefined") module.exports = DriveWatcherProfileCache;
`;
fs.writeFileSync(path.join(__dirname, "profile-cache.js"), body);
console.log(`profile-cache.js · ${(body.length / 1024).toFixed(0)} KB`);
